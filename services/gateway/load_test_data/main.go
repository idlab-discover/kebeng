type TestAccountData struct {
	Accounts []model.TestAccount `json:"accounts"`
	Keys     []model.TestKey     `json:"keys"`
	SSHKeys  []model.TestSSHKey  `json:"ssh_keys"`
}

type TestStoreData struct {
	Entries []model.TestSnapEntry `json:"snap_entries"`
}

// LoadTestData creates a set of test data by calling the client methods
// of the Account, Store, and Assertion services via the gateway.
func CreateTestData(baseHandler *util.BaseHandler) error {
	// Initialize the test handler
	h := &testHandler{
		BaseHandler: *baseHandler,
	}
	// Load test data from JSON files
	accountTestData, err := h.loadInAccountTestData()
	if err != nil {
		logrus.Errorf("Failed to load account test data: %v", err)
		return fmt.Errorf("failed to load account test data: %v", err)
	}
	storeTestData, err := h.loadInStoreTestData()
	if err != nil {
		logrus.Errorf("Failed to load store test data: %v", err)
		return fmt.Errorf("failed to load store test data: %v", err)
	}

	logrus.Infof("Loaded all the test data successfully.")

	// create maps so that id's can be mapped to correct actual id that is generated by db
	// since these are actual UUID's they should be unique so they don't overwrite each other
	accountIDMap := make(map[string]string)
	storeIDMap := make(map[string]string)
	assertionIDMap := make(map[string]string)

	// Load the test data into the database
	ctx := context.Background()

	err = h.loadInAccountDataInDB(ctx, accountTestData, accountIDMap, assertionIDMap)
	if err != nil {
		logrus.Errorf("Failed to load account data into DB: %v", err)
		return fmt.Errorf("failed to load account data into DB: %v", err)
	}

	err = h.loadInStoreDataInDB(ctx, storeTestData, storeIDMap, accountIDMap)
	if err != nil {
		logrus.Errorf("Failed to load store data into DB: %v", err)
		return fmt.Errorf("failed to load store data into DB: %v", err)
	}
	logrus.Infof("Loaded all the test data into the database successfully.")

	return nil
}

