// ################# LOAD TEST DATA ####################

func (h *testHandler) loadInAccountTestData() (*TestAccountData, error) {
	filePath := h.Config.TestDataFolderPath + "/account_data.json"
	// check if file exists
	if _, err := os.Stat(filePath); os.IsNotExist(err) {
		logrus.Errorf("Test data file does not exist: %s", filePath)
		return nil, fmt.Errorf("test data file does not exist: %s", filePath)
	}
	file, err := os.ReadFile(filePath)
	if err != nil {
		return nil, fmt.Errorf("failed to open test data file: %v", err)
	}
	// Load the test data from the JSON file
	storeTestData := &TestAccountData{}
	err = json.Unmarshal(file, storeTestData)
	if err != nil {
		return nil, fmt.Errorf("failed to unmarshal test data: %v", err)
	}
	return storeTestData, nil
}

